// CabExport.java - apply decode/names/*.json and export per-unit listings + decompiles.
// Headless: analyzeHeadless <proj> cab -process resident.bin -noanalysis -postScript CabExport.java <namesdir> <outdir>
// names json: { "SSSS:OOOO": "Name", ... }  (any number of files; later files win; USER_DEFINED names)
// Output per memory block (unit): <outdir>/<block>.lst (disassembly), <outdir>/<block>.c (decompile),
// plus <outdir>/functions.tsv. Stub thunk blocks go to stubs.lst only.
// Pascal string literals: an immediate operand v next to PUSH CS (or a DS reference) whose target bytes
// are a length-prefixed printable string gets an end-of-line comment  ; "text"  (heuristic, marked [ps]).
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.*;
import ghidra.program.model.listing.*;
import ghidra.program.model.symbol.*;
import ghidra.program.model.mem.*;
import ghidra.program.model.scalar.Scalar;
import ghidra.app.decompiler.*;
import java.io.*;
import java.nio.file.*;
import java.util.*;
import java.util.regex.*;

public class CabExport extends GhidraScript {
  Memory mem;

  String pstr(Address a) {
    try {
      MemoryBlock b = mem.getBlock(a);
      if (b == null || !b.isInitialized()) return null;
      int n = mem.getByte(a) & 0xff;
      if (n < 3 || n > 120) return null;
      if (b.getEnd().subtract(a) < n) return null;
      byte[] buf = new byte[n];
      mem.getBytes(a.add(1), buf);
      for (byte c : buf) if (c < 0x20 || c > 0x7e) return null;
      return new String(buf, "ISO-8859-1");
    } catch (Exception e) { return null; }
  }

  public void run() throws Exception {
    String[] a = getScriptArgs();
    File namesDir = new File(a[0]), out = new File(a[1]);
    out.mkdirs();
    mem = currentProgram.getMemory();
    if (currentProgram.getFunctionManager().getFunctionCount() < 600) {
      println("CabExport: REFUSING to export - program has only " + currentProgram.getFunctionManager().getFunctionCount() + " functions (failed build?)");
      return;
    }
    AddressFactory af = currentProgram.getAddressFactory();
    Listing listing = currentProgram.getListing();
    SymbolTable st = currentProgram.getSymbolTable();
    // names map
    // keys "SSSS:OOOO" or "DS:OOOO" (= 0C1C:OOOO, the module lanes' globals)
    Pattern p = Pattern.compile("\"((?:[0-9A-Fa-f]{4}|[Dd][Ss]):[0-9A-Fa-f]{4})\"\\s*:\\s*\"([^\"]+)\"");
    File[] nf = namesDir.listFiles((d, n) -> n.endsWith(".json"));
    int applied = 0;
    // Merge all files first. Precedence: a real name always beats a placeholder (g_XXXX[_hi|_N], RT_SSSS_OOOO,
    // FUN_/DAT_/LAB_); among real names (or among placeholders) the later file in name order wins.
    // Conflicts between two different real names are listed in <outdir>/NAMES_REPORT.md.
    Pattern ph = Pattern.compile("^(g_[0-9A-Fa-f]{4}(_hi|_[0-9A-Fa-f]+)?|RT_[0-9A-Fa-f]{4}_[0-9A-Fa-f]{4}|FUN_.*|DAT_.*|LAB_.*)$");
    Map<String, String[]> merged = new TreeMap<>();   // addr -> {name, file}
    List<String> conflicts = new ArrayList<>();
    int nreal = 0, nph = 0;
    if (nf != null) {
      Arrays.sort(nf);
      for (File f : nf) {
        Matcher m = p.matcher(new String(Files.readAllBytes(f.toPath())));
        while (m.find()) {
          String key = m.group(1).toUpperCase().replaceFirst("^DS:", "0C1C:");
          String nm = m.group(2).replaceAll("[^A-Za-z0-9_@.$]", "_");
          String[] old = merged.get(key);
          boolean newPh = ph.matcher(nm).matches();
          if (old != null) {
            boolean oldPh = ph.matcher(old[0]).matches();
            if (newPh && !oldPh) continue;               // keep the real name
            if (!newPh && !oldPh && !old[0].equals(nm))
              conflicts.add("| " + key + " | " + old[0] + " (" + old[1] + ") | " + nm + " (" + f.getName() + ") |");
          }
          merged.put(key, new String[]{nm, f.getName()});
        }
      }
    }
    for (Map.Entry<String, String[]> en : merged.entrySet()) {
      Address ad = af.getAddress(en.getKey());
      String nm = en.getValue()[0];
      if (ph.matcher(nm).matches()) nph++; else nreal++;
      try {
        Function fn = listing.getFunctionAt(ad);
        if (fn != null && !fn.isThunk()) fn.setName(nm, SourceType.USER_DEFINED);
        else st.createLabel(ad, nm, SourceType.USER_DEFINED).setPrimary();
        applied++;
      } catch (Exception e) { println("name failed " + en.getKey() + " " + nm + ": " + e); }
    }
    try (PrintWriter w = new PrintWriter(new File(out, "NAMES_REPORT.md"))) {
      w.println("# Names merge report (generated by CabExport.java; regenerate, do not edit)\n");
      w.println("Files (name order): " + (nf == null ? "" : Arrays.toString(Arrays.stream(nf).map(File::getName).toArray())));
      w.println("\nApplied " + applied + " names: " + nreal + " real, " + nph + " placeholders. Rule: a real name beats a placeholder (g_XXXX, RT_SSSS_OOOO, FUN_/DAT_/LAB_); among real names the later file wins.\n");
      w.println("## Conflicts between real names (" + conflicts.size() + "; the later file won)\n");
      w.println("| addr | earlier | later (applied) |\n|---|---|---|");
      for (String c : conflicts) w.println(c);
    }
    println("names applied: " + applied + " (real " + nreal + ", placeholder " + nph + ", conflicts " + conflicts.size() + ")");
    // routines that never return (from the names map): keeps callers' decompiles from running into padding
    for (Function f : listing.getFunctions(true))
      if (f.getName().matches("System\\.(Halt|@RunError|@DivideError)")) f.setNoReturn(true);

    DecompInterface di = new DecompInterface();
    DecompileOptions opt = new DecompileOptions();
    di.setOptions(opt);
    di.openProgram(currentProgram);
    Map<String, PrintWriter[]> files = new TreeMap<>();
    PrintWriter tsv = new PrintWriter(new File(out, "functions.tsv"));
    tsv.println("unit\tname\taddr\tbytes\tcallers\tcallees\tstrings");
    FunctionIterator it = listing.getFunctions(true);
    int n = 0, fail = 0;
    while (it.hasNext()) {
      Function f = it.next();
      MemoryBlock blk = mem.getBlock(f.getEntryPoint());
      String unit = blk == null ? "unknown" : blk.getName();
      boolean stub = unit.startsWith("stub_");
      String key = stub ? "stubs" : unit;
      PrintWriter[] w = files.get(key);
      if (w == null) {
        w = new PrintWriter[]{new PrintWriter(new File(out, key + ".lst")), stub ? null : new PrintWriter(new File(out, key + ".c"))};
        w[0].println("; " + key + " - generated by CabExport.java from ghidra_proj/cab; regenerate, do not edit");
        if (w[1] != null) w[1].println("/* " + key + " - generated by CabExport.java; regenerate, do not edit */");
        files.put(key, w);
      }
      Set<String> callers = new TreeSet<>(), callees = new TreeSet<>(), strs = new LinkedHashSet<>();
      for (Function c : f.getCallingFunctions(monitor)) callers.add(c.getName());
      for (Function c : f.getCalledFunctions(monitor)) callees.add(c.isThunk() && c.getThunkedFunction(true) != null ? c.getThunkedFunction(true).getName() : c.getName());
      StringBuilder sb = new StringBuilder();
      sb.append("\n;==== ").append(f.getName()).append(" @ ").append(f.getEntryPoint())
        .append("  bytes=").append(f.getBody().getNumAddresses());
      if (f.isThunk() && f.getThunkedFunction(true) != null) sb.append("  thunk-> ").append(f.getThunkedFunction(true).getName());
      sb.append("\n;     callers: ").append(String.join(", ", callers)).append("\n");
      InstructionIterator ii = listing.getInstructions(f.getBody(), true);
      Instruction prev = null;
      List<Instruction> ins = new ArrayList<>();
      while (ii.hasNext()) ins.add(ii.next());
      for (int i = 0; i < ins.size(); i++) {
        Instruction in = ins.get(i);
        Address ad = in.getAddress();
        Symbol s = st.getPrimarySymbol(ad);
        if (s != null && !ad.equals(f.getEntryPoint())) sb.append(s.getName()).append(":\n");
        byte[] by = in.getBytes();
        StringBuilder hx = new StringBuilder();
        for (byte b : by) hx.append(String.format("%02x", b & 0xff));
        String line = String.format("  %s  %-14s %s", ad, hx, in.toString());
        String cmt = null;
        // calls: show callee name
        for (Reference r : in.getReferencesFrom()) {
          if (r.getReferenceType().isOverride()) {
            Function c = listing.getFunctionAt(r.getToAddress());
            cmt = "-> " + r.getToAddress() + (c != null ? " " + c.getName() : "") + " [near target fixed]";
          } else if (r.getReferenceType().isCall() || r.getReferenceType().isJump()) {
            Function c = listing.getFunctionAt(r.getToAddress());
            if (c != null) { Function t = c.isThunk() ? c.getThunkedFunction(true) : null; cmt = (t != null ? t.getName() + " (via " + c.getName() + ")" : c.getName()); }
          } else if (r.getReferenceType().isData()) {
            String ps = pstr(r.getToAddress());
            if (ps != null) { cmt = "[ps] \"" + ps + "\""; strs.add(String.format("ds:%x=%s", ((SegmentedAddress) r.getToAddress()).getSegmentOffset(), ps)); }
            else {
              MemoryBlock db = mem.getBlock(r.getToAddress());
              Symbol gs = st.getPrimarySymbol(r.getToAddress());
              if (db != null && db.getName().equals("dseg") && gs != null && gs.getSource() == SourceType.USER_DEFINED) cmt = gs.getName();
            }
          }
        }
        if (cmt == null) {
          boolean pushCs = (i > 0 && ins.get(i - 1).toString().equals("PUSH CS")) || (i + 1 < ins.size() && ins.get(i + 1).toString().equals("PUSH CS"))
              || (i + 2 < ins.size() && ins.get(i + 2).toString().equals("PUSH CS"));
          if (pushCs) {
            for (int op = 0; op < in.getNumOperands(); op++) {
              Object[] objs = in.getOpObjects(op);
              if (objs.length == 1 && objs[0] instanceof Scalar && in.getOperandRefType(op) != null) {
                long v = ((Scalar) objs[0]).getUnsignedValue();
                if (v > 0xffff) continue;
                SegmentedAddress sa = (SegmentedAddress) ad;
                Address t = ((SegmentedAddressSpace) sa.getAddressSpace()).getAddress(sa.getSegment(), (int) v);
                String ps = pstr(t);
                if (ps != null) { cmt = "[ps] cs:\"" + ps + "\""; strs.add(String.format("%x=%s", v, ps)); }
              }
            }
          }
        }
        String ec = listing.getComment(CommentType.EOL, ad);
        if (ec != null) cmt = (cmt == null ? "" : cmt + " ") + ec.replace('\n', ' ');
        sb.append(cmt == null ? line : String.format("%-60s ; %s", line, cmt)).append("\n");
      }
      w[0].print(sb);
      tsv.println(key + "\t" + f.getName() + "\t" + f.getEntryPoint() + "\t" + f.getBody().getNumAddresses() + "\t"
          + String.join(",", callers) + "\t" + String.join(",", callees) + "\t" + String.join(" | ", strs).replace('\t', ' '));
      if (w[1] != null) {
        DecompileResults r = di.decompileFunction(f, 90, monitor);
        String c = (r != null && r.getDecompiledFunction() != null) ? r.getDecompiledFunction().getC() : null;
        if (c == null) { fail++; c = "/* decompile failed: " + (r == null ? "" : r.getErrorMessage()) + " */\n"; }
        w[1].println("\n/* ==== " + f.getName() + " @ " + f.getEntryPoint() + (strs.isEmpty() ? "" : "  strings: " + String.join(" | ", strs).replace("*/", "*_/")) + " */");
        w[1].print(c);
      }
      n++;
    }
    for (PrintWriter[] w : files.values()) { w[0].close(); if (w[1] != null) w[1].close(); }
    tsv.close(); di.dispose();
    println("exported functions: " + n + ", decompile failures: " + fail);
  }
}
