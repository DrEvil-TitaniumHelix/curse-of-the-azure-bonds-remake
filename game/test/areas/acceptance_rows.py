"""Generate the ACCEPTANCE.md "Areas (cab-build-areas)" section from decode/pseudo/SCREENS_INDEX.md.

One row per SCREENS_INDEX id whose source row is VIEW_SCREENS, PARTY_SCREENS, MAGIC_SCREENS or COMBAT_SCREENS (the units
cab-build-areas translated), grouped by the SCREENS_INDEX sections, with the DOSBox-X references that exist
(acceptance/ref/REF-<id>[-variant].capture.json). Existing verdicts in ACCEPTANCE.md are kept (keyed by id); new rows
start as `pending`. Usage (repo root): python -I game/test/areas/acceptance_rows.py [--write]
"""
import os
import re
import sys

sys.stdout.reconfigure(encoding='utf-8')

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
IDX = os.path.join(ROOT, 'decode', 'pseudo', 'SCREENS_INDEX.md')
ACC = os.path.join(ROOT, 'ACCEPTANCE.md')
REF = os.path.join(ROOT, 'acceptance', 'ref')
MINE = ('VIEW_SCREENS', 'PARTY_SCREENS', 'MAGIC_SCREENS', 'COMBAT_SCREENS')
HEAD = '## Areas (cab-build-areas)'


def cells(line):
    return [c.strip() for c in line.strip().strip('|').split('|')]


def main():
    refs = sorted(f[:-len('.capture.json')] for f in os.listdir(REF) if f.endswith('.capture.json'))
    acc = open(ACC, encoding='utf-8').read()
    if HEAD not in acc:
        sys.exit('ACCEPTANCE.md has no "%s" section' % HEAD)
    before, after = acc.split(HEAD, 1)
    tail_m = re.search(r'\n## (?!Areas)', after)                  # a later section (none today)
    mine_old, rest = (after[:tail_m.start()], after[tail_m.start():]) if tail_m else (after, '')
    kept = {}
    for line in mine_old.splitlines():
        if line.startswith('| S'):
            c = cells(line)
            if len(c) >= 6:
                kept[c[0]] = c

    out = [HEAD, '',
           'Rows: every SCREENS_INDEX id from VIEW / PARTY / MAGIC / COMBAT_SCREENS (the VIEW, PARTY, MAGIC and COMBAT units in',
           '`game/areas/`). Generated by `python -I game/test/areas/acceptance_rows.py --write` (keeps the verdict columns).',
           'Routes and verdicts are filled when the engine can drive the game there (ECL host, engine M2/M3); `pending` = not',
           'run yet. Unit tests of the routines behind these screens: `node game/test/areas/run_all.mjs`.', '']
    section, total, withref = None, 0, 0
    verdicts = {}
    counts = {}
    for line in open(IDX, encoding='utf-8'):
        if line.startswith('## ') and not line.startswith('## 0.'):
            section = line[3:].strip()
            continue
        if not line.startswith('| S'):
            continue
        c = cells(line)
        sid, src = c[0], c[1]
        if not src.startswith(MINE):
            continue
        if section not in counts:
            counts[section] = 0
            out += ['', '### ' + section, '| id | source | routine / trigger | build path | reference | px | verdict |',
                    '|---|---|---|---|---|---|---|']
        counts[section] += 1
        total += 1
        r = [x for x in refs if x == 'REF-' + sid or x.startswith('REF-' + sid + '-')]
        if r:
            withref += 1
        trig = c[2].replace('|', '/')
        if len(trig) > 70:
            trig = trig[:67] + '...'
        old = kept.get(sid)
        path, px, verdict = (old[3], old[5], old[6]) if old and len(old) >= 7 else ('—', '—', 'pending' if r else 'pending (NO-REF yet)')
        if r and verdict == 'pending (NO-REF yet)':                # a reference was shot since
            verdict = 'pending'
        out.append('| %s | %s | %s | %s | %s | %s | %s |' % (sid, src, trig, path, ', '.join(r) or '—', px, verdict))
        key = (verdict.strip('* ').split(' ') or ['?'])[0].strip('*') + (' (NO-REF yet)' if 'NO-REF yet' in verdict else '')
        verdicts[key] = verdicts.get(key, 0) + 1
    out += ['', 'Summary Areas: %d rows (%s), %d with a DOSBox-X reference; verdicts: %s.' %
            (total, ', '.join('%s %d' % (s.split(' ')[0].rstrip('.'), n) for s, n in counts.items()), withref,
             ', '.join('%s %d' % kv for kv in sorted(verdicts.items()))), '']
    text = before + '\n'.join(out) + rest
    if '--write' in sys.argv:
        open(ACC, 'w', encoding='utf-8', newline='\n').write(text)
        print('ACCEPTANCE.md: %d area rows, %d with references' % (total, withref))
    else:
        print('\n'.join(out))


if __name__ == '__main__':
    main()
