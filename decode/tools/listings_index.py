"""Write decode/listings/INDEX.md from decode/listings/functions.tsv (CabExport.java output).

Usage: python listings_index.py [decode/listings]
"""
import csv, os, sys
from collections import defaultdict

d = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "listings")
rows = list(csv.DictReader(open(os.path.join(d, "functions.tsv"), encoding="latin-1"), delimiter="\t"))
units = defaultdict(list)
for r in rows:
    units[r["unit"]].append(r)


def key(u):
    return (u.startswith("ov"), u)


out = ["# Listings index (generated by decode/tools/listings_index.py; regenerate, do not edit)", "",
       "Per unit: `<unit>.lst` = disassembly per function, `<unit>.c` = Ghidra decompile per function; "
       "`functions.tsv` = name/addr/size/callers/callees/strings. Addresses are seg:off, resident image base 0000, "
       "overlay unit N at the analysis segment in decode/LAYOUT.md (2000.., 0x100-aligned) (see decode/LAYOUT.md). Names flow in from `decode/names/*.json` on "
       "`decode/tools/ghidra_build.sh export`.", "",
       "| unit | functions | named (non-default) | bytes | first | last |", "|---|---|---|---|---|---|"]
tot = 0
for u in sorted(units, key=key):
    fs = units[u]
    named = sum(1 for r in fs if not (r["name"].startswith("FUN_") or r["name"].startswith("ov") or r["name"].startswith("stub_")))
    by = sum(int(r["bytes"]) for r in fs)
    addrs = sorted(r["addr"] for r in fs)
    out.append("| %s | %d | %d | %d | %s | %s |" % (u, len(fs), named, by, addrs[0], addrs[-1]))
    tot += len(fs)
import glob, re
stray = sum(len(re.findall(r"DAT_109a_", open(f, encoding="latin-1").read())) for f in glob.glob(os.path.join(d, "*.c")))
out += ["", "Total functions: %d in %d units." % (tot, len(units)),
        "", "DS view check: `DAT_109a_*` occurrences in .c = %d (must be 0: DS 0C1C..150C is one block `dseg`, so every "
        "DS global prints as `DAT_0c1c_XXXX` = DS:XXXX, or by its decode/names name)." % stray]
if stray:
    print("WARNING: %d DAT_109a_ names - DS block split regressed" % stray)
open(os.path.join(d, "INDEX.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out))
