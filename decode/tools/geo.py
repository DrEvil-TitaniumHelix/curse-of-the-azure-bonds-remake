#!/usr/bin/env python3
"""Render / dump Pool of Radiance GEO maps (16x16 dungeon/town maps). Spec: decode/data/GEO.md.

Record (1026 B): u16 hdr (=0x0400, ignored by Load3DMap) + 4 planes x 256 B, cell index = y*16 + x.
  plane 0: hi nibble = wall type N, lo = wall type E
  plane 1: hi nibble = wall type S, lo = wall type W
  plane 2: cell attribute byte (read into DS:6AB1 on each move; semantics = ECL lane)
  plane 3: 2-bit passage/door state per side: bits 1-0 N, 3-2 E, 5-4 S, 7-6 W

Usage: geo.py render   -> decode/data/png/GEO/<FILE>_<id>.png (+ INDEX lines in decode/data/png/GEO/INDEX.md)
       geo.py dump FILE/ID
"""
import os
import sys

from PIL import Image, ImageDraw

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..', '..'))
BIN = os.path.join(ROOT, 'decode', 'bin', 'dax')
OUT = os.path.join(ROOT, 'decode', 'data', 'png', 'GEO')

DIRS = ('N', 'E', 'S', 'W')


def parse(b):
    assert len(b) == 0x402, len(b)
    cells = {}
    for y in range(16):
        for x in range(16):
            i = 2 + y * 16 + x
            p0, p1, p2, p3 = b[i], b[i + 256], b[i + 512], b[i + 768]
            cells[x, y] = {'wall': (p0 >> 4, p0 & 15, p1 >> 4, p1 & 15),
                           'door': (p3 & 3, (p3 >> 2) & 3, (p3 >> 4) & 3, (p3 >> 6) & 3),
                           'attr': p2}
    return cells


# wall colour by slot (type 1-5 slot 1, 6-10 slot 2, 11-15 slot 3); door state overrides
SLOT_COL = {1: (255, 255, 255), 2: (85, 255, 255), 3: (255, 255, 85)}
DOOR_COL = {0: None, 1: None, 2: (255, 85, 85), 3: (255, 85, 255)}
C = 24


def render(b):
    cells = parse(b)
    img = Image.new('RGB', (16 * C + 1, 16 * C + 1), (0, 0, 0))
    d = ImageDraw.Draw(img)
    for (x, y), c in cells.items():
        x0, y0 = x * C, y * C
        a = c['attr']
        if a:
            d.rectangle([x0 + 1, y0 + 1, x0 + C - 1, y0 + C - 1], fill=(40, 40, 70) if a & 0x80 else (30, 60, 30))
            d.text((x0 + 3, y0 + 7), '%02x' % a, fill=(150, 150, 150))
        seg = {'N': (x0, y0, x0 + C, y0), 'E': (x0 + C, y0, x0 + C, y0 + C),
               'S': (x0, y0 + C, x0 + C, y0 + C), 'W': (x0, y0, x0, y0 + C)}
        inset = {'N': (0, 2), 'E': (-2, 0), 'S': (0, -2), 'W': (2, 0)}
        for k, dn in enumerate(DIRS):
            t = c['wall'][k]
            ds = c['door'][k]
            if not t and not ds:
                continue
            dx, dy = inset[dn]
            x1, y1, x2, y2 = seg[dn]
            col = SLOT_COL[(t - 1) // 5 + 1] if t else (90, 90, 90)
            if DOOR_COL.get(ds):
                col = DOOR_COL[ds]
            width = 1 if ds == 1 and t else 2
            d.line([x1 + dx, y1 + dy, x2 + dx, y2 + dy], fill=col, width=width)
    return img


def main(argv):
    if len(argv) >= 2 and argv[1] == 'render':
        os.makedirs(OUT, exist_ok=True)
        lines = ['# GEO map renders (generated by decode/tools/geo.py)', '',
                 'Cell = 24 px, north up (y grows downward = south). Each side is drawn just inside its own cell, '
                 'so a shared wall shows as a double line (one per cell). Colour = wall slot (white = types 1-5 / '
                 'wallset slot 1, cyan = 6-10 / slot 2, yellow = 11-15 / slot 3); thin line = door state 1 on a wall; '
                 'red = door state 2, magenta = door state 3; grey = door state without wall type. '
                 'Shaded cells show the plane-2 attribute byte (hex; blue = bit 7 set). Spec: ../../GEO.md.', '']
        for fname in sorted(f for f in os.listdir(BIN) if f.startswith('GEO')):
            for fn in sorted(os.listdir(os.path.join(BIN, fname)), key=lambda s: int(s[:-4])):
                b = open(os.path.join(BIN, fname, fn), 'rb').read()
                pn = '%s_%s.png' % (fname, fn[:-4])
                render(b).save(os.path.join(OUT, pn), optimize=True)
                lines.append('- [%s/%s](%s)' % (fname, fn[:-4], pn))
        with open(os.path.join(OUT, 'INDEX.md'), 'w', newline='\n') as f:
            f.write('\n'.join(lines) + '\n')
        print('rendered', len(lines) - 4)
        return 0
    if len(argv) >= 3 and argv[1] == 'dump':
        fname, rid = argv[2].split('/')
        cells = parse(open(os.path.join(BIN, fname, rid + '.bin'), 'rb').read())
        for y in range(16):
            print(' '.join('%s/%s/%02x' % (''.join('%x' % t for t in cells[x, y]['wall']),
                                           ''.join(str(s) for s in cells[x, y]['door']), cells[x, y]['attr'])
                           for x in range(16)))
        return 0
    print(__doc__)
    return 1


if __name__ == '__main__':
    sys.exit(main(sys.argv))
